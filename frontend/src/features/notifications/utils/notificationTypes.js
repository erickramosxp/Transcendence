export const NOTIFICATION_TYPES = {
	LIKE_POST: "LIKE_POST",
	LIKE_COMMENT: "LIKE_COMMENT",
	COMMENT_POST: "COMMENT_POST",
	FRIEND_REQUEST: "FRIEND_REQUEST",
	FRIEND_ACCEPTED: "FRIEND_ACCEPTED",
	FRIEND_REJECTED: "FRIEND_REJECTED",
	FRIEND_BROKEN: "FRIEND_BROKEN",
	ADDED_GROUP: "ADDED_GROUP",
	REMOVED_GROUP: "REMOVED_GROUP",
};

export const NOTIFICATION_TYPE_VALUES = Object.values(NOTIFICATION_TYPES);

export function isNotificationType(value) {
	return NOTIFICATION_TYPE_VALUES.includes(value);
}
